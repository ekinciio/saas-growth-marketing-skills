def _read_text_arg(value: str) -> str:
    if value == "-":
        return sys.stdin.read()
    with open(value, encoding="utf-8-sig") as handle:
        return handle.read()


def main(argv: Optional[List[str]] = None) -> int:
    """CLI: save / path / previous. Prints JSON to stdout; exit 2 on bad input."""
    parser = argparse.ArgumentParser(
        prog="report",
        description="Save a growth report under growth-reports/ in the current folder.",
    )
    sub = parser.add_subparsers(dest="command")
    for name, text in (
        ("save", "write the report, the JSON sidecar and the footer"),
        ("path", "print where the report would be written"),
        ("previous", "print the previous run of this skill and subject"),
    ):
        command = sub.add_parser(name, help=text)
        command.add_argument("--skill", required=True)
        command.add_argument("--subject", required=True, help="URL or name the report is about")
        command.add_argument("--date", help="YYYY-MM-DD (default: today)")
        if name == "save":
            command.add_argument("--markdown", required=True, help="report text file, or '-' for stdin")
            command.add_argument("--data", help="JSON file with the values to keep and compare")
            command.add_argument("--compare", nargs="*", help="dotted paths to compare (default: all)")
    args = parser.parse_args(argv)
    if not args.command:
        parser.print_usage(sys.stderr)
        return 2
    try:
        if args.command == "path":
            paths = report_paths(args.skill, args.subject, args.date)
            print(json.dumps({"status": "ok", "markdown": _display_path(paths["markdown"]),
                              "json": _display_path(paths["json"])}))
            return 0
        if args.command == "previous":
            previous = find_previous_run(args.skill, args.subject, before=args.date)
            print(json.dumps({"status": "ok", "previous_run": previous}, ensure_ascii=False, default=str))
            return 0
        markdown = _read_text_arg(args.markdown)
        data = None
        if args.data:
            data = json.loads(_read_text_arg(args.data))
            if not isinstance(data, dict):
                raise ValueError("--data must hold a JSON object")
        saved = write_report(args.skill, args.subject, markdown, data, args.date,
                             compare_paths=args.compare or None)
        print(json.dumps(dict(status="ok", **saved), ensure_ascii=False, default=str))
        return 0
    except (OSError, ValueError) as exc:
        print("report: error: %s" % exc, file=sys.stderr)
        print(json.dumps({"status": "usage_error", "errors": [str(exc)], "notes": []}))
        return 2


