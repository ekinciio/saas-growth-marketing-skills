"""Report output: growth-reports/<YYYY-MM-DD>-<skill>-<slug>.md plus a JSON sidecar.

Reports go to a growth-reports/ folder in the CURRENT working directory
(the user's project), never next to the skill. On first use the folder gets
a .gitignore containing '*', so client reports are private by default and
cannot be committed by accident.

    from _growthkit import report
    saved = report.write_report(
        skill="landing-page-cro",
        subject="https://www.notion.com",
        markdown=report_text,          # without the footer
        data={"scores": {"total": 72}, "facts": {...}},
    )
    saved["markdown_path"]  # growth-reports/2026-10-24-landing-page-cro-notion-com.md

write_report() looks for the previous run of the same skill and subject,
adds a "## Change since last run" section (values compared from the JSON
sidecars), and ends the file with the standard footer.

The model usually writes the report text itself, so the same steps are
available from the command line (run from the user's project folder):

    PYTHONPATH="${CLAUDE_SKILL_DIR}/scripts" python3 -m _growthkit.report save \\
        --skill landing-page-cro --subject https://www.notion.com \\
        --markdown draft.md --data facts.json

    python3 "${CLAUDE_SKILL_DIR}/scripts/_growthkit/report.py" previous \\
        --skill landing-page-cro --subject https://www.notion.com
"""

from __future__ import annotations

import os
import sys

if __name__ == "__main__" and not __package__:
    # Run as a file (python3 .../_growthkit/report.py). Drop this folder from
    # sys.path, because its http.py and html.py would shadow the standard
    # library modules of the same name, then import it as a package so the
    # relative imports below work.
    _here = os.path.dirname(os.path.abspath(__file__))
    sys.path[:] = [p for p in sys.path if os.path.abspath(p or os.curdir) != _here]
    sys.path.insert(0, os.path.dirname(_here))
    __package__ = os.path.basename(_here)
    __import__(__package__)

import argparse  # noqa: E402
import json  # noqa: E402
import re  # noqa: E402
import tempfile  # noqa: E402
import unicodedata  # noqa: E402
from datetime import date as _date  # noqa: E402
from typing import Any, Dict, List, Optional, Tuple, Union  # noqa: E402
from urllib.parse import urlparse  # noqa: E402

from . import REPO_SHORT, TOOLKIT_NAME, __version__  # noqa: E402

REPORTS_DIRNAME = "growth-reports"
CHANGE_HEADING = "## Change since last run"

# The exact footer every SKILL.md asks for. CI checks reports against it.
FOOTER_TEMPLATE = (
    "---\n"
    "*Report generated by {skill} | " + TOOLKIT_NAME + "*\n"
    "*GitHub: " + REPO_SHORT + "*\n"
)

_FOOTER_RE = re.compile(
    r"\n*(?:-{3,}\s*\n)?\*Report generated by [^\n]*\| " + re.escape(TOOLKIT_NAME)
    + r"\*\s*\n\*GitHub: [^\n]*\*\s*$"
)
_DATE_RE = re.compile(r"^\d{4}-\d{2}-\d{2}$")
# Sidecar keys that describe the run rather than the subject; never diffed.
_META_KEYS = {"generated_at", "toolkit_version", "version", "tool", "demo", "errors", "notes", "status"}


def footer(skill: str) -> str:
    """The standard report footer for a skill (ends with a newline)."""
    return FOOTER_TEMPLATE.format(skill=skill)


