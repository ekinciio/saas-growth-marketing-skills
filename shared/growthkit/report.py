def slugify(text: str, max_len: int = 60) -> str:
    """ASCII, lower-case, hyphen-separated: 'Acme Kafe & Co.' -> 'acme-kafe-co'."""
    value = (text or "").replace("\u0131", "i").replace("\u0130", "I")  # Turkish dotless i
    value = unicodedata.normalize("NFKD", value).encode("ascii", "ignore").decode("ascii")
    value = re.sub(r"[^a-zA-Z0-9]+", "-", value).strip("-").lower()
    if len(value) > max_len:
        value = value[:max_len].rstrip("-")
    return value


def subject_slug(subject: str, max_len: int = 60) -> str:
    """Slug for a report subject. URLs use host and path without 'www.'.

    'https://www.notion.com/' -> 'notion-com'
    'linear.app/pricing'      -> 'linear-app-pricing'
    'Acme Coffee, Austin'     -> 'acme-coffee-austin'
    """
    value = (subject or "").strip()
    candidate = value if re.match(r"^https?://", value, re.I) else "https://" + value
    if re.match(r"^https?://", value, re.I) or re.match(r"^[\w-]+(?:\.[\w-]+)+(?:[/:?#]|$)", value):
        try:
            parsed = urlparse(candidate)
            host = (parsed.hostname or "").lower()
            if host.startswith("www."):
                host = host[4:]
            if host:
                value = host + (parsed.path or "").rstrip("/")
        except ValueError:
            pass
    return slugify(value, max_len) or "report"


def _skill_slug(skill: str) -> str:
    slug = slugify(skill, 60)
    if not slug:
        raise ValueError("skill name is empty")
    return slug


def _date_text(value: Union[None, str, _date]) -> str:
    if value is None:
        return _date.today().isoformat()
    if isinstance(value, _date):
        return value.isoformat()
    text = str(value).strip()
    if not _DATE_RE.match(text):
        raise ValueError("date must be YYYY-MM-DD, got %r" % value)
    _date.fromisoformat(text)  # validates the calendar date
    return text


def reports_dir(base_dir: Optional[str] = None) -> str:
    """growth-reports/ under base_dir (default: the current working directory)."""
    return os.path.join(base_dir or os.getcwd(), REPORTS_DIRNAME)


def ensure_reports_dir(base_dir: Optional[str] = None) -> str:
    """Create growth-reports/ and its '*' .gitignore when missing. Returns the folder."""
    folder = reports_dir(base_dir)
    os.makedirs(folder, exist_ok=True)
    ignore = os.path.join(folder, ".gitignore")
    if not os.path.exists(ignore):
        with open(ignore, "w", encoding="utf-8") as handle:
            handle.write("*\n")
    return folder


def report_paths(
    skill: str,
    subject: str,
    date: Union[None, str, _date] = None,
    base_dir: Optional[str] = None,
) -> Dict[str, str]:
    """Planned paths for a report: {"dir", "markdown", "json", "slug", "skill", "date"}."""
    skill_slug = _skill_slug(skill)
    slug = subject_slug(subject)
    day = _date_text(date)
    folder = reports_dir(base_dir)
    stem = "%s-%s-%s" % (day, skill_slug, slug)
    return {
        "dir": folder,
        "markdown": os.path.join(folder, stem + ".md"),
        "json": os.path.join(folder, stem + ".json"),
        "slug": slug,
        "skill": skill_slug,
        "date": day,
    }


def _display_path(path: str) -> str:
    """Path relative to the working directory when possible (no home paths in reports)."""
    try:
        relative = os.path.relpath(path)
    except ValueError:
        return path
    return path if relative.startswith("..") else relative


