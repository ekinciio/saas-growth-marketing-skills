def strip_footer(markdown: str) -> str:
    """Remove a trailing standard footer so it is never written twice."""
    return _FOOTER_RE.sub("", markdown.rstrip()).rstrip()


def _atomic_write(path: str, text: str) -> None:
    folder = os.path.dirname(path)
    handle, temp = tempfile.mkstemp(prefix=".tmp-", dir=folder)
    try:
        with os.fdopen(handle, "w", encoding="utf-8", newline="\n") as out:
            out.write(text)
        os.replace(temp, path)
    except BaseException:
        try:
            os.unlink(temp)
        except OSError:
            pass
        raise


def write_report(
    skill: str,
    subject: str,
    markdown: str,
    data: Optional[Dict[str, Any]] = None,
    date: Union[None, str, _date] = None,
    base_dir: Optional[str] = None,
    compare_paths: Optional[List[str]] = None,
    add_change_section: bool = True,
) -> Dict[str, Any]:
    """Write the report and its JSON sidecar. Returns paths and the comparison.

    - Creates growth-reports/ and growth-reports/.gitignore ('*').
    - A same-day rerun overwrites that day's files; the comparison is always
      against the latest run from an EARLIER day.
    - Appends '## Change since last run' unless the text already has it.
    - Ends with the standard footer (an existing footer is replaced).

    Returns {"markdown_path", "json_path", "previous_run", "changes"} with
    paths relative to the working directory when possible.
    """
    paths = report_paths(skill, subject, date, base_dir)
    ensure_reports_dir(base_dir)
    previous = find_previous_run(skill, subject, before=paths["date"], base_dir=base_dir)
    changes: List[Dict[str, Any]] = []
    if previous and previous.get("data") is not None and data is not None:
        changes = diff_data(previous["data"], data, compare_paths)

    body = strip_footer(markdown or "")
    if add_change_section and CHANGE_HEADING.lower() not in body.lower():
        body = body + "\n\n" + change_section(previous, changes, paths["date"]).rstrip()
    text = body.strip("\n") + "\n\n" + footer(paths["skill"])
    _atomic_write(paths["markdown"], text)

    sidecar = {
        "report": {
            "skill": paths["skill"],
            "subject": subject,
            "slug": paths["slug"],
            "date": paths["date"],
            "toolkit_version": __version__,
            "markdown": os.path.basename(paths["markdown"]),
            "previous_run": previous["date"] if previous else None,
        },
        "changes_since_last_run": changes,
        "data": data if data is not None else {},
    }
    _atomic_write(paths["json"], json.dumps(sidecar, ensure_ascii=False, indent=2, default=str) + "\n")
    return {
        "markdown_path": _display_path(paths["markdown"]),
        "json_path": _display_path(paths["json"]),
        "previous_run": (
            {"date": previous["date"], "markdown": _display_path(previous["markdown"]) if previous["markdown"] else None}
            if previous else None
        ),
        "changes": changes,
    }


