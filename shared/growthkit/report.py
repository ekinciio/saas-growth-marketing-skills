# Previous runs
# ---------------------------------------------------------------------------


def _load_json(path: str) -> Optional[Any]:
    try:
        with open(path, encoding="utf-8") as handle:
            return json.load(handle)
    except (OSError, ValueError):
        return None


def find_previous_run(
    skill: str,
    subject: str,
    before: Union[None, str, _date] = None,
    base_dir: Optional[str] = None,
) -> Optional[Dict[str, Any]]:
    """Latest earlier report of the same skill and subject, or None.

    Matches file names exactly (<date>-<skill>-<slug>.md/.json), so
    'notion-com' never matches 'notion-com-pricing'. With before=None the
    latest run of any date is returned; otherwise only runs dated strictly
    before it. Returns {"date", "markdown", "json", "data"} where data is
    the sidecar's "data" object (None when there is no readable sidecar).
    """
    folder = reports_dir(base_dir)
    if not os.path.isdir(folder):
        return None
    skill_slug = _skill_slug(skill)
    slug = subject_slug(subject)
    limit = _date_text(before) if before is not None else None
    pattern = re.compile(
        r"^(\d{4}-\d{2}-\d{2})-%s-%s\.(md|json)$" % (re.escape(skill_slug), re.escape(slug))
    )
    runs: Dict[str, Dict[str, Any]] = {}
    for name in os.listdir(folder):
        match = pattern.match(name)
        if not match:
            continue
        day, ext = match.groups()
        if limit is not None and day >= limit:
            continue
        entry = runs.setdefault(day, {"date": day, "markdown": None, "json": None, "data": None})
        entry["markdown" if ext == "md" else "json"] = os.path.join(folder, name)
    for day in sorted(runs, reverse=True):
        entry = runs[day]
        if entry["json"]:
            sidecar = _load_json(entry["json"])
            if isinstance(sidecar, dict):
                meta = sidecar.get("report") or {}
                # Guard against an ambiguous name such as skill "geo" with
                # slug "seo-auditor-x" colliding with skill "geo-seo-auditor".
                if meta.get("skill") not in (None, skill_slug) or meta.get("slug") not in (None, slug):
                    continue
                entry["data"] = sidecar.get("data")
        return entry
    return None


def _flatten(data: Any, prefix: str = "") -> Dict[str, Any]:
    """{'a': {'b': 1}} -> {'a.b': 1}. Lists and meta keys are skipped."""
    flat: Dict[str, Any] = {}
    if isinstance(data, dict):
        for key, value in data.items():
            if not prefix and key in _META_KEYS:
                continue
            path = "%s.%s" % (prefix, key) if prefix else str(key)
            if isinstance(value, dict):
                flat.update(_flatten(value, path))
            elif isinstance(value, (list, tuple)):
                continue
            else:
                flat[path] = value
    return flat


def diff_data(
    previous: Any,
    current: Any,
    paths: Optional[List[str]] = None,
    limit: int = 30,
) -> List[Dict[str, Any]]:
    """Changed values between two sidecar data objects.

    Compares scalar leaves by dotted path (lists are ignored). With paths,
    only those are compared. Each change: {"path", "previous", "current",
    "delta"} where delta is set for numbers.
    """
    before = _flatten(previous or {})
    after = _flatten(current or {})
    keys = paths if paths is not None else list(after) + [k for k in before if k not in after]
    changes: List[Dict[str, Any]] = []
    for key in keys:
        old = before.get(key)
        new = after.get(key)
        if old == new:
            continue
        delta = None
        numeric = (int, float)
        if isinstance(old, numeric) and isinstance(new, numeric) and not isinstance(old, bool) \
                and not isinstance(new, bool):
            delta = round(new - old, 4)
        changes.append({"path": key, "previous": old, "current": new, "delta": delta})
        if len(changes) >= limit:
            break
    return changes


def _cell(value: Any) -> str:
    if value is None:
        return "-"
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, float):
        text = ("%.2f" % value).rstrip("0").rstrip(".")
        return text if text not in ("", "-0") else "0"
    text = " ".join(str(value).split())
    if len(text) > 60:
        text = text[:57] + "..."
    return text.replace("|", "\\|")


def _delta_cell(delta: Optional[float]) -> str:
    if delta is None:
        return "changed"
    if delta == 0:
        return "0"
    return ("+" if delta > 0 else "") + _cell(float(delta) if not float(delta).is_integer() else int(delta))


def change_section(
    previous: Optional[Dict[str, Any]],
    changes: List[Dict[str, Any]],
    current_date: str,
) -> str:
    """Markdown for '## Change since last run'."""
    lines = [CHANGE_HEADING, ""]
    if not previous:
        lines.append("First run for this subject. The next run will compare against this one.")
        return "\n".join(lines) + "\n"
    where = _display_path(previous.get("markdown") or previous.get("json") or "")
    lines.append("Previous run: %s (%s)." % (previous["date"], where))
    lines.append("")
    if previous.get("data") is None:
        lines.append("The previous run has no JSON sidecar, so values could not be compared automatically.")
        return "\n".join(lines) + "\n"
    if not changes:
        lines.append("No tracked values changed since %s." % previous["date"])
        return "\n".join(lines) + "\n"
    lines.append("| Value | %s | %s | Change |" % (previous["date"], current_date))
    lines.append("|---|---|---|---|")
    for change in changes:
        lines.append("| %s | %s | %s | %s |" % (
            _cell(change["path"]), _cell(change["previous"]), _cell(change["current"]),
            _delta_cell(change["delta"]),
        ))
    return "\n".join(lines) + "\n"


